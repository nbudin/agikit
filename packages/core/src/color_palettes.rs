use serde::{Deserialize, Serialize};
use tsify::Tsify;
use wasm_bindgen::prelude::wasm_bindgen;

pub type Color = [u8; 4];

#[derive(Tsify, Serialize, Deserialize)]
#[tsify(into_wasm_abi, from_wasm_abi)]
pub struct ColorPalette {
    pub name: String,
    #[tsify(type = "[number, number, number, number][]")]
    pub colors: [Color; 16],
}

#[wasm_bindgen(js_name = "egaPalette")]
pub fn ega_palette() -> ColorPalette {
    ColorPalette {
        name: "EGA".to_string(),
        colors: [
            [0x00, 0x00, 0x00, 0xff],
            [0x00, 0x00, 0xaa, 0xff],
            [0x00, 0xaa, 0x00, 0xff],
            [0x00, 0xaa, 0xaa, 0xff],
            [0xaa, 0x00, 0x00, 0xff],
            [0xaa, 0x00, 0xaa, 0xff],
            [0xaa, 0x55, 0x00, 0xff],
            [0xaa, 0xaa, 0xaa, 0xff],
            [0x55, 0x55, 0x55, 0xff],
            [0x55, 0x55, 0xff, 0xff],
            [0x55, 0xff, 0x55, 0xff],
            [0x55, 0xff, 0xff, 0xff],
            [0xff, 0x55, 0x55, 0xff],
            [0xff, 0x55, 0xff, 0xff],
            [0xff, 0xff, 0x55, 0xff],
            [0xff, 0xff, 0xff, 0xff],
        ],
    }
}
